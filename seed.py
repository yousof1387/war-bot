def seed_weapons():
    count = 0
    for country_name, categories in WEAPONS.items():
        country = session.query(Country).filter_by(name=country_name).first()
        if not country:
            continue
        for cat, units in categories.items():
            if not isinstance(units, list):
                continue
            for u in units:
                # ✅ اصلاح شده: len(u) < 8
                if not isinstance(u, tuple) or len(u) < 8:
                    continue
                
                name = u[0]
                exists = session.query(MilitaryUnitType).filter_by(
                    name=name, country_id=country.id
                ).first()
                if exists:
                    continue
                
                session.add(MilitaryUnitType(
                    name=u[0],
                    category=cat,
                    country_id=country.id,
                    weapon_type=u[1],
                    range_km=u[2],
                    emoji=u[3],
                    attack_power=u[4],
                    defense_power=u[5],
                    cost=u[6],
                    upkeep_cost=round(u[6] / 250, 1),
                    required_level=u[7],
                ))
                count += 1
    session.commit()
    print(f"✅ {count} تجهیزات نظامی اضافه شد.")
